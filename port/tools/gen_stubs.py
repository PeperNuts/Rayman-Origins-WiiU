"""Generate gen/stubs.S for the Rayman Origins Wii U port.

For every Wii platform symbol the game references (undef.txt, already prefixed in the game
object as wii_<name>), emit one of:
  - nothing, if src/*.c defines wii_<name> (hand-written implementation)
  - the original Wii machine code, if the function is self-contained (no relocations,
    no privileged instructions, no hardware addresses) - per undef_info.json "copyable"
  - the original data bytes (render modes etc.), or zeros
  - a tracing stub: records the call (stub_hit) and returns a neutral value

usage: gen_stubs.py undef.txt undef_info.json symbols.txt main.dol src_dir out.S
"""
import json
import os
import re
import struct
import sys

undef_path, info_path, symbols_path, dol_path, src_dir, out_path = sys.argv[1:7]

names = ['wii_' + l.strip() if not l.strip().startswith('wii_') else l.strip() for l in open(undef_path) if l.strip()]
info = json.load(open(info_path))

syms = {}
for l in open(symbols_path):
    m = re.match(r'(\S+) = (\S+):0x([0-9A-Fa-f]+); // type:(\w+)(?: size:0x([0-9A-Fa-f]+))?', l)
    if m:
        syms[m.group(1)] = (m.group(2), int(m.group(3), 16), m.group(4), int(m.group(5) or '0', 16))

dol = open(dol_path, 'rb').read()
offs = struct.unpack('>18I', dol[0:72])
addrs = struct.unpack('>18I', dol[72:144])
sizes = struct.unpack('>18I', dol[144:216])


def dol_bytes(addr, n):
    for o, a, s in zip(offs, addrs, sizes):
        if s and a <= addr and addr + n <= a + s:
            return dol[o + (addr - a):o + (addr - a) + n]
    return None


implemented = set()
for fn in os.listdir(src_dir):
    if fn.endswith(('.c', '.S')):
        for m in re.finditer(r'\bwii_([A-Za-z0-9_]+)\s*(?:\(|=|;|:)', open(os.path.join(src_dir, fn)).read()):
            implemented.add(m.group(1))

# Neutral return values that steer the game down its "not available" paths.
RETURNS = {
    'DVDConvertPathToEntrynum': -1,
    'DVDFastOpen': 0,
    'WPADProbe': -1,           # WPAD_ERR_NO_CONTROLLER
    'NANDOpen': -1, 'NANDCreate': -1, 'NANDRead': -1, 'NANDWrite': -1, 'NANDSeek': -1,
    'NANDGetLength': -1, 'NANDMove': -1, 'NANDCheck': -1, 'NANDReadAsync': -1,
    'NANDWriteAsync': -1, 'NANDSimpleSafeOpen': -1, 'NANDSimpleSafeClose': -1,
    'NANDGetHomeDir': -1, 'NANDClose': -1,
}

ZERO_DATA = {'_eti_init_info': 32}  # empty C++ exception table index (terminator only)

out = ['# Generated by tools/gen_stubs.py - do not edit.', '    .section .text', '    .align 2']
data = ['    .section .data', '    .align 3']
strings = ['    .section .rodata', '    .align 2']
stats = {'implemented': 0, 'copied_code': 0, 'data': 0, 'stub': 0}

for i, n in enumerate(names):
    if not n.startswith('wii_'):
        raise SystemExit(f'unexpected undefined symbol {n}')
    base = n[4:]
    if base in implemented:
        stats['implemented'] += 1
        continue
    ent = info.get(base, {})
    s = syms.get(base)
    if base in ZERO_DATA:
        data += [f'    .global {n}', f'{n}:', f'    .space {ZERO_DATA[base]}']
        stats['data'] += 1
        continue
    if s and s[2] == 'object':
        b = dol_bytes(s[1], s[3])
        if b is None:
            raise SystemExit(f'no bytes for {base}')
        data += [f'    .global {n}', '    .align 2', f'{n}:']
        data += ['    .byte ' + ','.join(str(x) for x in b[k:k + 16]) for k in range(0, len(b), 16)]
        stats['data'] += 1
        continue
    if ent.get('copyable') and s and s[2] == 'function':
        b = dol_bytes(s[1], s[3])
        out += [f'    .global {n}', f'    .type {n}, @function', f'{n}:  # original Wii code from 0x{s[1]:08X}']
        out += ['    .long ' + ','.join('0x%08X' % struct.unpack('>I', b[k:k + 4])[0] for k in range(j, min(j + 16, len(b)), 4))
                for j in range(0, len(b), 16)]
        out += [f'    .size {n}, .-{n}']
        stats['copied_code'] += 1
        continue
    # Linker-folded trivial bodies that only have an address-style name (e.g. Lock_800101C0):
    # copy the original instructions up to the first blr if the body is branch-free.
    m = re.search(r'_([0-9A-F]{8})$', base)
    if m and not s:
        addr = int(m.group(1), 16)
        b = dol_bytes(addr, 32)
        words = [struct.unpack('>I', b[k:k + 4])[0] for k in range(0, len(b), 4)] if b else []
        if 0x4E800020 in words:
            body = words[:words.index(0x4E800020) + 1]
            if all((w >> 26) not in (16, 18, 19) or w == 0x4E800020 for w in body):
                out += [f'    .global {n}', f'    .type {n}, @function', f'{n}:  # original Wii code from 0x{addr:08X}',
                        '    .long ' + ','.join('0x%08X' % w for w in body), f'    .size {n}, .-{n}']
                stats['copied_code'] += 1
                continue
    ret = RETURNS.get(base, 0)
    out += [f'    .global {n}', f'    .type {n}, @function', f'{n}:',
            f'    lis 3, .Lname{i}@ha', f'    addi 3, 3, .Lname{i}@l', f'    li 4, {ret}', '    b stub_hit',
            f'    .size {n}, .-{n}']
    strings += [f'.Lname{i}:', f'    .asciz "{base}"']
    stats['stub'] += 1

open(out_path, 'w').write('\n'.join(out + [''] + data + [''] + strings) + '\n')
print(stats)
